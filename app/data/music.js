// ─── Helpers ───────────────────────────────────────────────────
export function getTrackBySlug(slug) {
  return TRACKS.find((t) => t.slug === slug) ?? null
}

export function getAdjacentTracks(slug) {
  const idx  = TRACKS.findIndex((t) => t.slug === slug)
  return {
    prev: idx > 0              ? TRACKS[idx - 1] : null,
    next: idx < TRACKS.length - 1 ? TRACKS[idx + 1] : null,
  }
}
